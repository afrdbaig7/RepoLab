import { execFile } from "node:child_process";
import { mkdtemp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { promisify } from "node:util";

const run = promisify(execFile);
const manager = process.env.npm_execpath;
if (!manager) throw new Error("Run through pnpm run package:smoke so its executable is explicit");
const javascriptManager = /\.(?:c|m)?js$/i.test(manager);
const pm = (...args) => run(javascriptManager ? process.execPath : manager, javascriptManager ? [manager, ...args] : args, { timeout: 120000, maxBuffer: 2 * 1024 * 1024, windowsHide: true });
await mkdir("output/packages", { recursive: true });
await pm("--filter", "@repolab/lens", "pack", "--pack-destination", resolve("output/packages"));
const archive = resolve("output/packages/repolab-lens-0.1.0.tgz");
const modules = await readFile("node_modules/.modules.yaml", "utf8");
const store = modules.trimStart().startsWith("{") ? JSON.parse(modules).storeDir : modules.match(/^storeDir: (.+)$/m)?.[1]?.trim();
if (!store) throw new Error("Cannot locate the verified dependency store from the installed workspace");
const root = await mkdtemp(join(tmpdir(), "lens-install-"));
try {
  await writeFile(join(root, "package.json"), JSON.stringify({ private: true, dependencies: { "@repolab/lens": `file:${archive.replaceAll("\\", "/")}` } }));
  await pm("--dir", root, "install", "--offline", "--ignore-scripts", "--store-dir", store, "--config.confirmModulesPurge=false");
  const cli = join(root, "node_modules/@repolab/lens/dist/cli.js");
  const env = { ...process.env };
  delete env.LENS_WORKER;
  const doctor = JSON.parse((await run(process.execPath, [cli, "doctor"], { env, timeout: 10000 })).stdout);
  if (!doctor.ready) throw new Error("Installed package doctor failed");
  const fixture = JSON.parse(await readFile("fixtures/lens/cases.json", "utf8"));
  const repository = join(root, "repository");
  await mkdir(repository);
  const git = async (...args) => (await run("git", ["-C", repository, ...args], { timeout: 10000 })).stdout.trim();
  await git("init", "-b", "main");
  await git("config", "user.name", "Lens package fixture");
  await git("config", "user.email", "fixture@example.invalid");
  await git("config", "commit.gpgsign", "false");
  for (const [path, content] of Object.entries(fixture.before)) await writeFile(join(repository, path), content);
  await git("add", "."); await git("commit", "-m", "before");
  const base = await git("rev-parse", "HEAD");
  for (const [path, content] of Object.entries(fixture.after)) await writeFile(join(repository, path), content);
  await git("add", "."); await git("commit", "-m", "after");
  const head = await git("rev-parse", "HEAD");
  const config = join(root, "config.json");
  await writeFile(config, JSON.stringify(fixture.config));
  const invocation = run(process.execPath, [cli, "review", "--repo", repository, "--base", base, "--head", head, "--policy", "exact", "--config", config, "--format", "json"], { env, timeout: 30000, maxBuffer: 2 * 1024 * 1024 });
  const result = await invocation.catch(error => { if (error.code === 3) return error; throw error; });
  const report = JSON.parse(result.stdout);
  if (report.findings.length !== 6) throw new Error("Installed package did not analyze the seeded repository");
  await writeFile("output/package-smoke.json", JSON.stringify({ platform: `${process.platform}-${process.arch}`, archive, doctor, findings: report.findings.map(finding => finding.ruleId), workspaceLinks: false, lifecycleScripts: false, passed: true }, null, 2) + "\n");
  console.log("Fresh tarball installation passed: doctor and six-rule real Git review, no workspace links or lifecycle scripts.");
} finally { await rm(root, { recursive: true, force: true }); }
