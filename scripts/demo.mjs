import { execFile } from "node:child_process";
import { mkdir, mkdtemp, readFile, writeFile } from "node:fs/promises";
import { resolve, join } from "node:path";
import { promisify } from "node:util";
import { cpus, release, totalmem } from "node:os";
import { capture } from "../packages/lens/dist/snapshot.js";
import { runAnalysis } from "../packages/lens/dist/analysis.js";
import { render } from "../packages/lens/dist/render.js";

await mkdir("output", { recursive: true });
const root = await mkdtemp(resolve("output/seeded-demo-"));
const worker = resolve(`target/debug/lens-snapshot${process.platform === "win32" ? ".exe" : ""}`);
const execute = promisify(execFile);
const git = async (...args) => (await execute("git", ["-C", root, ...args], { env: { ...process.env, GIT_AUTHOR_DATE: "2026-11-04T00:00:00Z", GIT_COMMITTER_DATE: "2026-11-04T00:00:00Z" } })).stdout.trim();
await git("init", "-b", "main");
await git("config", "user.name", "Lens seeded fixture");
await git("config", "user.email", "fixture@example.invalid");
await git("config", "core.autocrlf", "false");
await git("config", "commit.gpgsign", "false");
const fixture = JSON.parse(await readFile("fixtures/lens/cases.json", "utf8"));
const before = fixture.before["api.ts"];
for (const [path, content] of Object.entries(fixture.before)) await writeFile(join(root, path), content);
await git("add", "."); await git("commit", "-m", "Seeded baseline, not a real vulnerability");
const base = await git("rev-parse", "HEAD");
for (const [path, content] of Object.entries(fixture.after)) await writeFile(join(root, path), content);
await git("add", "."); await git("commit", "-m", "Seeded supported review observations");
const head = await git("rev-parse", "HEAD");
await git("checkout", "-b", "legitimate-refactor", base);
await writeFile(join(root, "api.ts"), before.replace("return id;", "return id.trim();"));
await git("add", "."); await git("commit", "-m", "Legitimate body refactor with unchanged protection and API");
const refactor = await git("rev-parse", "HEAD");
const results = [];
for (const [name, target, expected] of [["seeded", head, fixture.expected], ["refactor", refactor, fixture.refactor.expected]]) {
  const started = performance.now();
  const snapshot = await capture(root, base, target, "exact", undefined, worker);
  const captured = performance.now();
  const report = await runAnalysis({ before: snapshot.before, after: snapshot.after, manifest: snapshot.manifest, config: fixture.config });
  const analyzed = performance.now();
  const detected = report.findings.map(finding => finding.ruleId).sort();
  if (JSON.stringify(detected) !== JSON.stringify(expected)) throw new Error(`${name}: unexpected rule observations ${detected}`);
  for (const format of ["json", "html", "markdown", "terminal"]) await writeFile(`output/${name}-report.${{ json: "json", html: "html", markdown: "md", terminal: "txt" }[format]}`, render(report, format));
  const rendered = performance.now();
  results.push({ case: name, expected, detected, milliseconds: Math.round(rendered - started), stagesMs: { snapshot: Math.round(captured - started), analysis: Math.round(analyzed - captured), render: Math.round(rendered - analyzed) }, files: report.run.files, bytes: report.run.bytes, unresolvedCalls: report.run.unresolvedCalls, completeness: report.run.completeness });
}
const evaluation = { dataset: "frozen-original-seeded-v1", author: "Lens workspace contributors, MIT", thirdPartySource: false, humanReviewSpeedExperiment: false, cases: results, platform: `${process.platform}-${process.arch}`, node: process.version, machine: { cpu: cpus()[0]?.model, logicalCpus: cpus().length, systemMemoryBytes: totalmem(), osRelease: release() }, peakRssBytes: process.resourceUsage().maxRSS * 1024, note: "Two synthetic cases; not public-PR precision, security effectiveness or user time savings. Timings include bounded analysis worker startup/trusted libraries and rendering. Peak RSS describes the Node process including semantic threads, not combined Rust/Git memory.", commits: { base, head, refactor }, repository: root };
await writeFile("output/evaluation.json", JSON.stringify(evaluation, null, 2) + "\n");
await writeFile("output/demo-config.json", JSON.stringify({ schemaVersion: 1, guards: ["requireOwner"] }, null, 2) + "\n");
await writeFile("output/demo-path.txt", root + "\n");
console.log(JSON.stringify(evaluation, null, 2));
